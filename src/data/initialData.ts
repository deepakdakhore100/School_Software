export function generateAllGradeSections(): GradeSectionUnit[] {
  const units: GradeSectionUnit[] = [];
  
  ALL_GRADES.forEach((grade, gradeIndex) => {
    ALL_SECTIONS.forEach((section, secIndex) => {
      const roomNum =
        grade === 'Nursery' || grade === 'KG1' || grade === 'KG2'
          ? `EarlyBlock-0${gradeIndex + 1}0${secIndex + 1}`
          : Number(grade) <= 5
          ? `Primary-10${gradeIndex}0${secIndex + 1}`
          : Number(grade) <= 8
          ? `Middle-20${gradeIndex}0${secIndex + 1}`
          : `Senior-30${gradeIndex}0${secIndex + 1}`;

      const floor =
        grade === 'Nursery' || grade === 'KG1' || grade === 'KG2'
          ? 'Ground Floor'
          : Number(grade) <= 5
          ? 'First Floor'
          : Number(grade) <= 8
          ? 'Second Floor'
          : 'Third Floor';

      units.push({
        id: `UNIT-${grade}-${section}`,
        grade,
        section,
        roomNumber: roomNum,
        floor,
        classTeacherId: `STAFF-00${(secIndex % 8) + 3}`,
        classTeacherName:
          secIndex === 0
            ? 'Mrs. Ananya Sharma'
            : secIndex === 1
            ? 'Dr. Rajesh Tripathi'
            : secIndex === 2
            ? 'Mrs. Manjusha Patil'
            : 'Mrs. Kavita Verma',
        studentCapacity: 40,
        enrolledStudentsCount: 34 + ((gradeIndex * 3 + secIndex) % 7),
      });
    });
  });

  return units;
}

export function computeGradeAndPoint(percentage: number): {
  grade: string;
  gradePoint: number;
  remarks: string;
} {
  if (percentage >= 91) return { grade: 'A1', gradePoint: 10.0, remarks: 'Outstanding Performance' };
  if (percentage >= 81) return { grade: 'A2', gradePoint: 9.0, remarks: 'Excellent Performance' };
  if (percentage >= 71) return { grade: 'B1', gradePoint: 8.0, remarks: 'Very Good Progress' };
  if (percentage >= 61) return { grade: 'B2', gradePoint: 7.0, remarks: 'Good Understanding' };
  if (percentage >= 51) return { grade: 'C1', gradePoint: 6.0, remarks: 'Satisfactory / Above Average' };
  if (percentage >= 41) return { grade: 'C2', gradePoint: 5.0, remarks: 'Average - Scope for Growth' };
  if (percentage >= 33) return { grade: 'D', gradePoint: 4.0, remarks: 'Marginal Pass' };
  return { grade: 'E', gradePoint: 0.0, remarks: 'Needs Improvement / Failed' };
}

